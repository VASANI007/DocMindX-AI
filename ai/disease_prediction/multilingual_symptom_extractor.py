def _safe_parse_json(text: str) -> Optional[dict]:
    if not text or not isinstance(text, str):
        return None
    text = text.strip()
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except Exception:
            pass
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        try:
            return json.loads(text[start:end+1])
        except Exception:
            pass
    return None


class MultilingualSymptomExtractor:
    """
    Hybrid Generative AI (Groq & Gemini) + Clinical Knowledge Base Extractor.
    Understands free-form multilingual vernacular text (Hinglish, Hindi, Gujarati, English),
    identifies described symptoms, and optionally identifies the disease the user is asking about.

    CRITICAL: This extractor extracts ONLY what the user actually reported.
    It does NOT invent symptoms not present in the user's input.
    Medicine generation is NOT this module's responsibility.
    """
    def __init__(self):
        self.symptoms_df = self._load_symptoms_df()
        self.major_diseases_df = self._load_major_diseases_df()
        self.id_lookup = self._build_id_lookup()
        self.disease_keyword_map = self._build_disease_keyword_map()

    def _load_symptoms_df(self) -> pd.DataFrame:
        csv_path = os.path.join(DATASETS_DIR, "symptoms", "symptoms_master.csv")
        if os.path.exists(csv_path):
            try:
                return pd.read_csv(csv_path, encoding="utf-8")
            except Exception as exc:
                _logger.error("[SymptomExtractor] Failed to load symptoms_master.csv: %s", exc)
                return pd.DataFrame()
        return pd.DataFrame()

    def _load_major_diseases_df(self) -> pd.DataFrame:
        csv_path = os.path.join(DATASETS_DIR, "disease", "india_major_diseases.csv")
        if os.path.exists(csv_path):
            try:
                return pd.read_csv(csv_path, encoding="utf-8")
            except Exception as exc:
                _logger.error("[SymptomExtractor] Failed to load india_major_diseases.csv: %s", exc)
                return pd.DataFrame()
        return pd.DataFrame()

    def _build_id_lookup(self) -> Dict[str, str]:
        lookup = {}
        if not self.symptoms_df.empty:
            for _, row in self.symptoms_df.iterrows():
                sid = str(row.get("symptom_id", "")).strip().upper()
                name = str(row.get("symptom_name", "")).strip().lower()
                name_hi = str(row.get("symptom_name_hi", "")).strip().lower()
                name_gu = str(row.get("symptom_name_gu", "")).strip().lower()
                if sid:
                    lookup[name] = sid
                    if name_hi:
                        lookup[name_hi] = sid
                    if name_gu:
                        lookup[name_gu] = sid
        return lookup

    def _build_disease_keyword_map(self) -> List[Dict[str, Any]]:
        disease_entries = []
        if not self.major_diseases_df.empty:
            for _, row in self.major_diseases_df.iterrows():
                d_id = str(row.get("disease_id", ""))
                d_name = str(row.get("disease_name", ""))
                d_name_hi = str(row.get("disease_name_hi", ""))
                d_name_gu = str(row.get("disease_name_gu", ""))
                cat = str(row.get("category", ""))
                urgency = str(row.get("urgency", "Urgent Clinical Attention"))
                spec = str(row.get("specialist", "General Physician"))
                icd = str(row.get("icd_code", "N/A"))

                # Parse symptoms list
                raw_syms = row.get("symptoms", [])
                if isinstance(raw_syms, str):
                    try:
                        syms = ast.literal_eval(raw_syms) if raw_syms.startswith("[") else [s.strip() for s in raw_syms.split(",")]
                    except Exception:
                        syms = [s.strip() for s in raw_syms.split(",")]
                else:
                    syms = list(raw_syms) if isinstance(raw_syms, (list, tuple)) else []

                keywords = set()
                keywords.add(d_name.lower())
                if d_name_hi and str(d_name_hi).lower() != "nan":
                    keywords.add(d_name_hi.lower())
                if d_name_gu and str(d_name_gu).lower() != "nan":
                    keywords.add(d_name_gu.lower())
                # Note: Substring/token extraction removed to prevent false-positive symptom fabrication from disease names

                disease_entries.append({
                    "disease_id": d_id,
                    "disease_name": d_name,
                    "disease_name_hi": d_name_hi,
                    "disease_name_gu": d_name_gu,
                    "category": cat,
                    "category_icon": str(row.get("category_icon", "")),
                    "icd_code": icd,
                    "specialist": spec,
                    "urgency": urgency,
                    "priority": str(row.get("priority", "High")),
                    "symptoms": syms,  # disease's known symptoms (for reference only)
                    "diet": str(row.get("diet", "")),
                    "tests": row.get("tests", []),
                    "keywords": list(keywords)
                })
        return disease_entries

    def _find_matching_symptom_id(self, concept_name: str, fallback_id: str = ""):
        clean_name = str(concept_name).lower().strip()
        if clean_name in self.id_lookup:
            return self.id_lookup[clean_name], concept_name

        # Use canonical normalizer taxonomy resolution first
        resolved_id = canonical_normalizer.get_symptom_id(clean_name)
        if resolved_id:
            rec = canonical_normalizer.bridge.lookup_by_id(resolved_id)
            official = rec.get("symptom_name", concept_name) if rec else concept_name
            return resolved_id, official

        if not self.symptoms_df.empty:
            # Exact match check
            exact_match = self.symptoms_df[self.symptoms_df["symptom_name"].str.lower() == clean_name]
            if not exact_match.empty:
                return exact_match.iloc[0]["symptom_id"], exact_match.iloc[0]["symptom_name"]

        return fallback_id or None, concept_name

    def _extract_via_llm(self, user_text: str, user_lang: str = "en") -> Optional[dict]:
        """
        Uses Groq or Gemini to understand complex multilingual medical text.
        ANTI-FABRICATION: Extracts ONLY symptoms the user described.
        Does NOT invent symptoms. Does NOT recommend medicines.
        """
        lang_label = "Hindi" if user_lang == "hi" else "Gujarati" if user_lang == "gu" else "English"

        prompt = f"""You are DocMindX AI, a clinical symptom extraction engine.
Analyze this patient input in any language (English/Hindi/Gujarati/Hinglish):
"{user_text}"

CRITICAL RULES:
1. Extract ONLY symptoms the patient EXPLICITLY described in their input.
2. Do NOT invent, assume, or add symptoms not present in the text.
3. Do NOT recommend medicines — that is not your job.
4. If the patient mentions a disease name, record it as detected_disease.
5. The symptoms list must ONLY contain what was actually mentioned.
6. Use ICD-11 format for disease codes (not ICD-10).

Respond strictly in valid JSON:
{{
  "detected_disease": {{
    "name": "Disease name if explicitly mentioned, else null",
    "name_hi": "Hindi name or null",
    "name_gu": "Gujarati name or null",
    "category": "Clinical category",
    "icd_code": "ICD-11 code if known, else null",
    "specialist": "Relevant specialist",
    "urgency": "Urgency level"
  }},
  "symptoms": [
    {{
      "concept": "Exact symptom the user described",
      "display_name": "Translated display in {lang_label}",
      "symptom_id": "S-code if known, else null"
    }}
  ],
  "is_emergency": false,
  "clinical_summary": "Brief summary of what the patient described — based ONLY on their input"
}}

Translate display names to {lang_label}. Extract ONLY from the user's actual words."""

        # Primary: Gemini Multi-Key Failover Pool
        if gemini_pool.get_active_keys():
            gem_body = {
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {"temperature": 0.05, "responseMimeType": "application/json"}
            }
            res_g_data, model_used, _ = gemini_pool.execute_with_failover(
                payload=gem_body,
                models=_GEMINI_MODELS,
                timeout=10
            )
            if res_g_data:
                candidates = res_g_data.get("candidates", [])
                if candidates:
                    raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                    parsed = _safe_parse_json(raw_text)
                    if parsed and (parsed.get("symptoms") or parsed.get("detected_disease")):
                        _logger.info("[SymptomExtractor] Gemini %s SUCCESS via pool", model_used)
                        return self._format_llm_result(parsed, user_lang, source="Gemini AI Extraction")

        # Secondary: Groq
        if GROQ_API_KEY:
            for groq_model in _GROQ_MODELS:
                try:
                    headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
                    body = {
                        "model": groq_model,
                        "messages": [{"role": "user", "content": prompt}],
                        "temperature": 0.05
                    }
                    res = requests.post("https://api.groq.com/openai/v1/chat/completions", headers=headers, json=body, timeout=7)
                    if res.status_code == 200:
                        content = res.json()["choices"][0]["message"]["content"]
                        parsed = _safe_parse_json(content)
                        if parsed and (parsed.get("symptoms") or parsed.get("detected_disease")):
                            _logger.info("[SymptomExtractor] Groq %s SUCCESS", groq_model)
                            return self._format_llm_result(parsed, user_lang, source="Groq AI Extraction")
                    else:
                        _logger.warning("[SymptomExtractor] Groq %s returned HTTP %s", groq_model, res.status_code)
                except requests.exceptions.Timeout:
                    _logger.warning("[SymptomExtractor] Groq %s TIMEOUT", groq_model)
                except requests.exceptions.ConnectionError:
                    _logger.warning("[SymptomExtractor] Groq %s CONNECTION ERROR", groq_model)
                except Exception as exc:
                    _logger.error("[SymptomExtractor] Groq %s error: %s", groq_model, exc)

        _logger.warning("[SymptomExtractor] All AI providers failed — returning None")
        return None

    def _format_llm_result(self, parsed: dict, user_lang: str, source: str = "AI Extraction") -> dict:
        detected_items = []
        matched_symptom_ids = []
        matched_symptom_labels = []
        is_emergency = bool(parsed.get("is_emergency", False))
        detected_disease = parsed.get("detected_disease")
        # Normalize null detected_disease
        if detected_disease and not detected_disease.get("name"):
            detected_disease = None

        for sym in parsed.get("symptoms", []):
            concept = sym.get("concept", "Symptom")
            sid = sym.get("symptom_id")
            if not sid:
                sid, official_name = self._find_matching_symptom_id(concept)
            else:
                official_name = concept

            display_name = sym.get("display_name", concept)

            detected_items.append({
                "concept": concept,
                "icon": "",
                "symptom_id": sid,
                "official_name": official_name,
                "display_name": display_name,
                "category": "Clinical Symptom"
            })

            if sid not in matched_symptom_ids:
                matched_symptom_ids.append(sid)
            if official_name not in matched_symptom_labels:
                matched_symptom_labels.append(official_name)

        summary_text = parsed.get("clinical_summary", "")
        if not summary_text:
            d_name = detected_disease.get("name") if detected_disease else "reported symptoms"
            summary_text = f"Clinical pattern compatible with '{d_name}' based on {len(detected_items)} described symptoms."

        return {
            "detected_disease": detected_disease,
            "detected_symptoms": detected_items,
            "symptom_ids": matched_symptom_ids,
            "symptom_labels": matched_symptom_labels,
            "recommended_medicines": [],  # Medicines are NOT generated by this extractor
            "is_emergency": is_emergency,
            "summary_text": summary_text,
            "source": source,
            "is_live": True,
            "fallback_used": False,
            "fallback_reason": ""
        }

    def _extract_symptoms_from_text(self, clean_text: str) -> tuple:
        """
        ANTI-FABRICATION: Only extract symptoms that actually appear in the user's input text.
        Does NOT auto-populate all symptoms of a matched disease.
        """
        matched_symptom_ids = []
        matched_symptom_labels = []
        detected_items = []

        if not self.symptoms_df.empty:
            for _, row in self.symptoms_df.iterrows():
                s_name = str(row.get("symptom_name", ""))
                s_hi = str(row.get("symptom_name_hi", ""))
                s_gu = str(row.get("symptom_name_gu", ""))
                raw_sid = row.get("symptom_id")
                if not raw_sid or pd.isna(raw_sid):
                    continue
                sid = str(raw_sid).strip()

                # Build keyword list for this symptom
                kws = [s_name.lower()]
                if s_hi and s_hi.lower() != "nan":
                    kws.append(s_hi.lower())
                if s_gu and s_gu.lower() != "nan":
                    kws.append(s_gu.lower())

                # Only add if ACTUALLY found in user's text
                for kw in kws:
                    if kw and len(kw) >= 3 and kw in clean_text:
                        if s_name not in matched_symptom_labels:
                            matched_symptom_labels.append(s_name)
                            matched_symptom_ids.append(sid)
                            detected_items.append({
                                "concept": s_name,
                                "icon": "",
                                "symptom_id": sid,
                                "official_name": s_name,
                                "display_name": s_name,
                                "category": str(row.get("symptom_category", "General"))
                            })
                        break

        return detected_items, matched_symptom_ids, matched_symptom_labels

    def extract_symptoms_and_medicines(self, user_text: str, user_lang: str = "en") -> dict:
        """
        Parses free-text input via Online Generative LLM (Groq / Gemini) with
        local clinical knowledge base fallback.

        ANTI-FABRICATION:
        - AI is instructed to extract only what user described
        - Offline fallback extracts only symptoms found in user's text
        - Medicines are not generated by this module
        - Fallback is clearly labeled
        """
        if not user_text or not isinstance(user_text, str) or not user_text.strip():
            return {
                "detected_disease": None,
                "detected_symptoms": [],
                "symptom_ids": [],
                "symptom_labels": [],
                "normalized_symptoms": [],
                "duration_days": None,
                "recommended_medicines": [],
                "is_emergency": False,
                "summary_text": "",
                "source": "Empty",
                "is_live": False,
                "fallback_used": False,
                "fallback_reason": "No input text"
            }

        # 1. Generic Multilingual Normalization & Dataset Matching
        norm_symptoms = normalize_user_symptoms(user_text, patient_context={"lang_code": user_lang})
        
        # Extract duration days
        dur_label, dur_days = canonical_normalizer._extract_duration(user_text)

        # 1. Canonical Semantic Normalization (Language-Independent)
        canonical_res = canonical_normalizer.normalize(user_text, user_context={"lang": user_lang})

        # 2. Primary: Try Online Generative AI (Gemini → Groq)
        llm_result = self._extract_via_llm(user_text, user_lang=user_lang)
        if llm_result and (llm_result.get("detected_symptoms") or llm_result.get("detected_disease")):
            # ANTI-HALLUCINATION & NEGATION ENFORCEMENT:
            filtered_syms = []
            filtered_ids = []
            filtered_labels = []
            neg_set = set(canonical_res.negative_findings)
            for s in llm_result.get("detected_symptoms", []):
                concept_lower = s.get("concept", "").lower()
                if any(neg in concept_lower for neg in neg_set):
                    continue
                filtered_syms.append(s)
                if s.get("symptom_id") and s["symptom_id"] not in filtered_ids:
                    filtered_ids.append(s["symptom_id"])
                if s.get("official_name") and s["official_name"] not in filtered_labels:
                    filtered_labels.append(s["official_name"])

            # Merge matched items from norm_symptoms
            for ns in norm_symptoms:
                if ns.get("dataset_match") and ns.get("symptom_id"):
                    sid = ns["symptom_id"]
                    sname = ns.get("dataset_name") or ns["normalized_english"]
                    if sid not in filtered_ids:
                        filtered_ids.append(sid)
                    if sname not in filtered_labels:
                        filtered_labels.append(sname)

            llm_result["detected_symptoms"] = filtered_syms
            llm_result["symptom_ids"] = filtered_ids
            llm_result["symptom_labels"] = filtered_labels
            llm_result["normalized_symptoms"] = norm_symptoms
            llm_result["duration_days"] = dur_days
            llm_result["negative_findings"] = canonical_res.negative_findings
            llm_result["canonical_representation"] = canonical_res.to_dict()
            if canonical_res.clinical_attributes.get("has_emergency_red_flags") or canonical_res.clinical_attributes.get("bite_exposure"):
                llm_result["is_emergency"] = True
            return llm_result

        # 3. Canonical & Knowledge Base Fallback
        _logger.info("[SymptomExtractor] Using canonical normalization fallback (LOCAL)")
        if canonical_res.normalization_status == "failed" and not canonical_res.canonical_concepts and not canonical_res.exposure_ids and not norm_symptoms:
            return {
                "clinical_status": "insufficient_information",
                "detected_disease": None,
                "detected_symptoms": [],
                "symptom_ids": [],
                "symptom_labels": [],
                "normalized_symptoms": [],
                "duration_days": dur_days,
                "recommended_medicines": [],
                "is_emergency": False,
                "summary_text": "Insufficient clinical information to determine a differential pattern. Please describe your symptoms in more detail.",
                "source": "DocMindX Canonical Normalizer",
                "is_live": False,
                "fallback_used": True,
                "fallback_reason": "Insufficient clinical normalization",
                "canonical_representation": canonical_res.to_dict(),
                "negative_findings": canonical_res.negative_findings
            }

        # Build detected items from canonical concepts and norm_symptoms
        detected_items = []
        matched_symptom_ids = list(canonical_res.symptom_ids)
        matched_symptom_labels = []

        for ns in norm_symptoms:
            if ns.get("dataset_match") and ns.get("symptom_id"):
                sid = ns["symptom_id"]
                sname = ns.get("dataset_name") or ns["normalized_english"]
                if sid not in matched_symptom_ids:
                    matched_symptom_ids.append(sid)
                if sname not in matched_symptom_labels:
                    matched_symptom_labels.append(sname)
                detected_items.append({
                    "concept": sname,
                    "icon": "",
                    "symptom_id": sid,
                    "official_name": sname,
                    "display_name": sname,
                    "category": "Clinical Symptom"
                })

        for concept in canonical_res.canonical_concepts:
            label = concept.replace("_", " ").title()
            if label not in matched_symptom_labels:
                matched_symptom_labels.append(label)
            sid = self.id_lookup.get(label.lower()) or self.id_lookup.get(concept.lower())
            if not sid:
                sid = canonical_normalizer.get_symptom_id(label) or canonical_normalizer.get_symptom_id(concept)
            if sid and sid not in matched_symptom_ids:
                matched_symptom_ids.append(sid)

            if not any(d.get("official_name") == label for d in detected_items):
                detected_items.append({
                    "concept": label,
                    "icon": "",
                    "symptom_id": sid or "",
                    "official_name": label,
                    "display_name": label,
                    "category": "Clinical Finding"
                })

        is_emergency = bool(
            canonical_res.clinical_attributes.get("has_emergency_red_flags")
            or canonical_res.clinical_attributes.get("bite_exposure")
        )

        summary_parts = []
        if canonical_res.clinical_attributes.get("exposure_type") == "animal_bite":
            animal = canonical_res.clinical_attributes.get("animal_type", "animal").capitalize()
            region = canonical_res.clinical_attributes.get("anatomical_region", "limb").replace("_", " ")
            summary_parts.append(f"Reported {animal} bite on {region}.")
        elif matched_symptom_labels:
            summary_parts.append(f"Identified clinical presentation: {', '.join(matched_symptom_labels)}.")

        if canonical_res.negative_findings:
            neg_labels = [n.replace("_", " ").title() for n in canonical_res.negative_findings]
            summary_parts.append(f"Explicitly absent: {', '.join(neg_labels)}.")

        summary_text = " ".join(summary_parts) if summary_parts else "Clinical pattern extracted from description."

        return {
            "detected_disease": None,
            "detected_symptoms": detected_items,
            "symptom_ids": matched_symptom_ids,
            "symptom_labels": matched_symptom_labels,
            "normalized_symptoms": norm_symptoms,
            "duration_days": dur_days,
            "recommended_medicines": [],
            "is_emergency": is_emergency,
            "summary_text": summary_text,
            "source": "DocMindX Canonical Normalizer (API Fallback)",
            "is_live": False,
            "fallback_used": True,
            "fallback_reason": "AI providers unavailable; canonical normalization used",
            "canonical_representation": canonical_res.to_dict()
        }


_symptom_norm_cache: Dict[str, List[Dict[str, Any]]] = {}


def normalize_user_symptoms(user_text: str, patient_context: Optional[dict] = None) -> List[Dict[str, Any]]:
    """
    Centralized Generic Multilingual Symptom Normalization & Dataset Matching Layer.
    Converts natural-language patient phrases across ALL supported languages into
    normalized English clinical symptom concepts, validating against symptoms_master.csv.

    Output format:
    [
        {
            "user_phrase": "tav aave chhe",
            "normalized_english": "Fever",
            "dataset_match": True,
            "dataset_name": "Fever",
            "match_type": "ALIAS MATCH",
            "match_status": "Matched",
            "symptom_id": "S000001"
        },
        ...
    ]
    """
    if not user_text or not isinstance(user_text, str) or not user_text.strip():
        return []

    clean_key = user_text.strip().lower()
    if clean_key in _symptom_norm_cache:
        return [dict(x) for x in _symptom_norm_cache[clean_key]]

    patient_context = patient_context or {}
    user_lang = patient_context.get("lang_code") or patient_context.get("lang", "en")

    canonical_res = canonical_normalizer.normalize(user_text, user_context={"lang": user_lang})
    neg_set = {n.lower().replace("_", " ") for n in canonical_res.negative_findings}

    prompt = f"""You are DocMindX AI, an expert clinical symptom normalization system.
Analyze this patient text (which may be in English, Hindi, Gujarati, Roman Gujarati, Hinglish, Marathi, or mixed vernacular):
"{user_text}"

CRITICAL RULES:
1. Extract ALL distinct symptom phrases explicitly described by the patient. Do NOT stop at the first symptom.
2. For each symptom, output:
   - "user_phrase": exact phrase used by the patient in their text (e.g. "tav aave chhe", "galu bale chhe", "pag ma dukhe chhe", "chakar aave chhe", "नाक से पानी गिर रहा है").
   - "english_name": concise, human-readable English clinical symptom name (e.g. "Fever", "Burning Throat", "Leg Pain", "Dizziness", "Runny Nose", "Cough", "Abdominal Bloating").
3. DO NOT output a diagnosis, disease name, or medication as the symptom english_name. Normalization is not diagnosis.
4. If a symptom was explicitly stated as absent (negated, e.g. "no fever", "ताव નથી"), DO NOT include it as a symptom.
5. If the patient mentions a duration, extract duration_days as an integer (e.g. "2 divas thi" -> 2, "since yesterday" -> 1, "for two weeks" -> 14), else null.

Respond strictly in valid JSON:
{{
  "duration_days": 2,
  "symptoms": [
    {{
      "user_phrase": "tav aave chhe",
      "english_name": "Fever"
    }},
    {{
      "user_phrase": "galu bale chhe",
      "english_name": "Burning Throat"
    }}
  ]
}}"""

    extracted_symptoms_raw = []

    # Primary: Gemini Multi-Key Failover Pool
    if gemini_pool.get_active_keys():
        gem_body = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.05, "responseMimeType": "application/json"}
        }
        res_g_data, model_used, _ = gemini_pool.execute_with_failover(
            payload=gem_body,
            models=_GEMINI_MODELS,
            timeout=10
        )
        if res_g_data:
            candidates = res_g_data.get("candidates", [])
            if candidates:
                raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                parsed = _safe_parse_json(raw_text)
                if parsed and isinstance(parsed.get("symptoms"), list) and parsed["symptoms"]:
                    extracted_symptoms_raw = parsed["symptoms"]

    # Secondary: Groq LLM
    if not extracted_symptoms_raw and GROQ_API_KEY:
        for groq_model in _GROQ_MODELS:
            try:
                headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
                body = {
                    "model": groq_model,
                    "messages": [{"role": "user", "content": prompt}],
                    "temperature": 0.05
                }
                res = requests.post("https://api.groq.com/openai/v1/chat/completions", headers=headers, json=body, timeout=7)
                if res.status_code == 200:
                    content = res.json()["choices"][0]["message"]["content"]
                    parsed = _safe_parse_json(content)
                    if parsed and isinstance(parsed.get("symptoms"), list) and parsed["symptoms"]:
                        extracted_symptoms_raw = parsed["symptoms"]
                        break
            except Exception:
                pass

    # Tertiary: Canonical Local Fallback
    if not extracted_symptoms_raw:
        split_pattern = r"[,;.\n।!?]|(?:\b(?:and|aur|ane|aani|तथा|એક|અને|આણિ|आणि)\b)"
        clauses = [c.strip() for c in re.split(split_pattern, user_text, flags=re.IGNORECASE) if len(c.strip()) >= 2]
        if canonical_res.canonical_concepts:
            for concept in canonical_res.canonical_concepts:
                label = concept.replace("_", " ").title()
                extracted_symptoms_raw.append({
                    "user_phrase": user_text,
                    "english_name": label
                })
        elif clauses:
            for clause in clauses:
                match_det = canonical_normalizer.bridge.match_symptom_detailed(clause)
                if match_det.get("dataset_match"):
                    extracted_symptoms_raw.append({
                        "user_phrase": clause,
                        "english_name": match_det.get("dataset_name") or clause.title()
                    })
                else:
                    extracted_symptoms_raw.append({
                        "user_phrase": clause,
                        "english_name": clause.strip().title()
                    })

    normalized_list = []
    seen_english = set()

    for item in extracted_symptoms_raw:
        if not isinstance(item, dict):
            continue
        user_phrase = str(item.get("user_phrase") or "").strip()
        english_name = str(item.get("english_name") or item.get("concept") or user_phrase).strip()
        if not english_name:
            continue

        if any(neg in english_name.lower() or (user_phrase and neg in user_phrase.lower()) for neg in neg_set):
            continue

        match_info = canonical_normalizer.bridge.match_symptom_detailed(english_name)
        if not match_info.get("dataset_match") and user_phrase:
            match_phrase = canonical_normalizer.bridge.match_symptom_detailed(user_phrase)
            if match_phrase.get("dataset_match"):
                match_info = match_phrase

        is_matched = bool(match_info.get("dataset_match"))
        dataset_name = match_info.get("dataset_name") if is_matched else None
        match_type = match_info.get("match_type", "UNMATCHED")
        match_status = "Matched" if is_matched else "Not Matched"
        symptom_id = match_info.get("symptom_id") if is_matched else None

        dedup_key = (english_name.lower(), user_phrase.lower())
        if dedup_key in seen_english:
            continue
        seen_english.add(dedup_key)

        normalized_list.append({
            "user_phrase": user_phrase or english_name,
            "normalized_english": english_name,
            "dataset_match": is_matched,
            "dataset_name": dataset_name,
            "match_type": match_type,
            "match_status": match_status,
            "symptom_id": symptom_id
        })

    _symptom_norm_cache[clean_key] = normalized_list
    return [dict(x) for x in normalized_list]


